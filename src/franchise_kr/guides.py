def render_item(slug: str) -> Optional[str]:
    from . import static_files

    guide = by_slug(slug)
    if guide is None:
        return None
    root = static_files.base_url()
    canonical = f"{root}/guides/{guide['slug']}"
    points = "".join(f"<li>{_esc(row)}</li>" for row in guide.get("points") or [])
    checks = "".join(f"<li>{_esc(row)}</li>" for row in guide.get("checklist") or [])
    pitfalls = "".join(f"<li>{_esc(row)}</li>" for row in guide.get("pitfalls") or [])
    faq_rows = "".join(
        f"<details><summary>{_esc(question)}</summary><p>{_esc(answer)}</p></details>"
        for question, answer in faq_pairs(guide)
    )
    tags = "".join(f'<span class="tag">{_esc(word)}</span>' for word in guide.get("keywords") or [])
    cta = (
        f'<div class="linkcard"><p><b>내 조건을 넣으면 확인 항목으로 정리해 드립니다.</b><br>'
        f'브랜드명·가맹비·인테리어·숙고기간·영업지역을 넣고 10초 만에 확인하세요. '
        f'입력값은 저장하지 않습니다.</p>'
        f'<a class="btn-link" href="/#check">10초 체크</a></div>'
    )
    if not guide.get("law_keys"):
        cta = (
            f'<div class="linkcard"><p><b>창업비용을 낸 뒤 받을 수 있는 지원금은 GRNT에서 확인하세요.</b><br>'
            f'지역·업종·나이 조건으로 공고를 찾고 신청기간을 확인할 수 있습니다.</p>'
            f'<a class="btn-link" href="{GRANT_URL}" target="_blank" rel="noopener noreferrer">GRNT 열기</a></div>'
        )
    body = (
        f'<p class="crumb"><a href="/">FRNC</a> › <a href="{INDEX_PATH}">프랜차이즈 가이드</a> › '
        f'{_esc(guide["topic"])}</p>'
        f'<section class="card" style="margin-top:14px">'
        f'<span class="tag">{_esc(CATEGORY_LABEL.get(guide["category"], ""))}</span>'
        f'<h1 style="margin-top:10px">{_esc(guide["question"])}</h1>'
        f'<div class="answer"><b>한 줄 답</b><br>{_esc(guide["one_line"])}</div>'
        f'<div class="tagrow">{tags}</div>'
        f'<div class="section"><h3>{_esc(points_title(guide))}</h3><ul class="qlist">{points}</ul></div>'
        f'<div class="section"><h3>{_esc(checklist_title(guide))}</h3><ul class="qlist">{checks}</ul></div>'
        f'</section>'
        f'<section class="card"><h2>근거 조문</h2>'
        f'<p class="sub">법제처 국가법령정보 공동활용 OPEN API 실조회본에서 그대로 가져왔습니다. '
        f'최신 조문은 법제처에서 다시 확인하세요.</p>{_law_cards(guide)}</section>'
        f'<section class="card"><h2>흔한 오해</h2><ul class="qlist">{pitfalls}</ul></section>'
        f'<section class="card faq"><h2>자주 묻는 질문</h2>{faq_rows}</section>'
        f'<section class="card">{cta}</section>'
        + _related_html(guide)
    )
    return _page(f"{guide['question']} — {SERVICE_NAME}", guide["one_line"], body,
                 f"/guides/{guide['slug']}", json_ld_blocks(guide, canonical))


def llms_section(base: Optional[str] = None) -> str:
    from . import static_files

    root = static_files.base_url(base)
    lines = ["## 질문형 가이드 (사람·AI 공용)"]
    for guide in GUIDES:
        lines.append(f"- [{guide['topic']}]({root}/guides/{guide['slug']}): {guide['question']} "
                     f"— {guide['one_line']}")
    lines.append(f"- [가이드 전체]({root}{INDEX_PATH}): {len(GUIDES)}종 목록·카테고리.")
    lines.append("- 각 페이지는 FAQPage·BreadcrumbList·WebPage 구조화 데이터를 포함하고, "
                 "인용한 조문은 법제처 OPEN API 실조회본입니다. 판정은 확정이 아닙니다.")
    return "\n".join(lines) + "\n"
