def eun_neun(word: str) -> str:
    """받침 유무에 따라 '은/는'을 고른다('확인 순서는', '법이 정한 기준은')."""
    text = str(word or "").strip()
    if not text:
        return "은"
    last = text[-1]
    code = ord(last)
    if 0xAC00 <= code <= 0xD7A3:
        return "은" if (code - 0xAC00) % 28 else "는"
    return "은"


def faq_pairs(guide: Dict[str, Any]) -> List[Tuple[str, str]]:
    """FAQPage JSON-LD 에 넣을 질문·답 쌍(페이지 본문과 같은 문장을 쓴다)."""
    topic = guide["topic"]
    pairs = [
        (guide["question"], guide["one_line"]),
        (f"{topic}: {points_title(guide)}{eun_neun(points_title(guide))} 무엇인가요?",
         " ".join(guide.get("points") or [])),
        (f"{topic}: {checklist_question(guide)}", " ".join(guide.get("checklist") or [])),
        (f"{topic}: 흔히 하는 오해는 무엇인가요?", " ".join(guide.get("pitfalls") or [])),
    ]
    pairs += list(guide.get("faq") or [])
    return pairs


