def _law_cards(guide: Dict[str, Any]) -> str:
    rows = law_blocks(guide)
    if not rows:
        note = guide.get("law_note_ko") or (
            "이 페이지는 법령 조문을 인용하지 않습니다. 법령 판단은 다른 가이드와 정보공개서 원문에서 확인하세요.")
        return f'<p class="sub">{_esc(note)}</p>'
    cards = []
    for row in rows:
        cards.append(
            '<div class="lawcard">'
            f'<div class="k">{_esc(row.get("label_ko") or row.get("key"))}</div>'
            f'<p class="t">{_esc(row.get("law"))}</p>'
            f'<p class="x">{_esc(row.get("excerpt_ko"))}</p>'
            f'<span class="src">{_esc(row.get("effective_on"))} 시행 · '
            f'{_esc(row.get("source_url"))}</span>'
            "</div>"
        )
    return "".join(cards)


