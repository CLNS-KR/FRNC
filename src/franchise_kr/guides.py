def _json_ld(block: Dict[str, Any]) -> str:
    """JSON-LD 직렬화 — `</script>` 로 조기 종료되지 않게 꺾쇠와 앰퍼샌드를 이스케이프한다.

    JSON 에서 `\u003c`/`\u003e`/`\u0026` 은 같은 문자로 해석되므로 파서는 그대로 읽는다.
    """
    text = json.dumps(block, ensure_ascii=False, separators=(",", ":"))
    return text.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")


